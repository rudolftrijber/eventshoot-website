/**
 * Genereert src/data/werkPhotos.generated.ts uit public/DATA_EVENTSHOOT/SITE_IMAGES/EVENTFOTOS.
 *
 * De map is de bron: foto erin = op /werk, foto eruit = weg.
 * Volgorde is vast door elkaar gehusseld (niet op bestandsnaam), zodat de
 * galerij niet verspringt bij elke pageload.
 *
 * Run: node scripts/generate-werk-photos.mjs
 */

import { readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const PHOTO_DIR = join(__dirname, '../public/DATA_EVENTSHOOT/SITE_IMAGES/EVENTFOTOS')
const OUT_PATH = join(__dirname, '../src/data/werkPhotos.generated.ts')
const BASE = '/DATA_EVENTSHOOT/SITE_IMAGES/EVENTFOTOS'
const HERO_PREFERRED = 'eventshoot-57.jpg'

const ALTS = [
  'Eventfotografie congres Nederland',
  'Zakelijk evenement fotografie',
  'Seminar fotograaf',
  'Congres fotografie',
  'Professionele eventfotografie',
  'Ledendag fotografie',
  'Bedrijfsbijeenkomst fotografie',
  'Congres spreker fotografie',
  'Zakelijk event reportage',
  'Netwerkbijeenkomst fotografie',
]

function mixRank(name) {
  let h = 2166136261
  for (let i = 0; i < name.length; i++) {
    h ^= name.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

function run() {
  const files = readdirSync(PHOTO_DIR)
    .filter(f => /\.(jpe?g|png|webp)$/i.test(f) && !f.startsWith('.'))
    .sort((a, b) => mixRank(a) - mixRank(b) || a.localeCompare(b, 'nl'))

  if (files.length === 0) {
    console.error('✗ Geen foto\'s in SITE_IMAGES/EVENTFOTOS')
    process.exit(1)
  }

  const hero = files.includes(HERO_PREFERRED) ? HERO_PREFERRED : files[0]
  const photosLiteral = files
    .map((file, i) => `  { src: \`${BASE}/${file}\`, alt: '${ALTS[i % ALTS.length]}' },`)
    .join('\n')

  const body = `// Auto-generated by scripts/generate-werk-photos.mjs — do not edit manually.
// Bron: public/DATA_EVENTSHOOT/SITE_IMAGES/EVENTFOTOS/ — wat in de map staat, komt op /werk.

export const WERK_PHOTO_BASE = '${BASE}'

export const WERK_HERO = \`${BASE}/${hero}\`

export const WERK_PHOTOS = [
${photosLiteral}
]
`

  mkdirSync(dirname(OUT_PATH), { recursive: true })
  writeFileSync(OUT_PATH, body, 'utf8')
  console.log(`✓ werkPhotos.generated.ts — hero ${hero}, ${files.length} foto's door elkaar uit EVENTFOTOS`)
}

run()
