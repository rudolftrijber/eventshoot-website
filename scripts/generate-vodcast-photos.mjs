/**
 * Genereert src/data/vodcastPhotos.generated.ts uit public/DATA_EVENTSHOOT/SITE_IMAGES/VODCAST.
 *
 * De map is de bron: foto erin = op de pagina, foto eruit = weg.
 * Hero blijft RT202570.jpg zolang dat bestand in de map staat.
 *
 * Run: node scripts/generate-vodcast-photos.mjs
 */

import { readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const PHOTO_DIR = join(__dirname, '../public/DATA_EVENTSHOOT/SITE_IMAGES/VODCAST')
const OUT_PATH = join(__dirname, '../src/data/vodcastPhotos.generated.ts')
const BASE = '/DATA_EVENTSHOOT/SITE_IMAGES/VODCAST'

const HERO_PREFERRED = 'RT202570.jpg'
const LONGFORM_PREFERRED = ['Vodcast_2.jpg', 'Vodcast_10.jpg', 'Vodcast_5.jpg']
const SHORTFORM_PREFERRED = ['Vodcast_3.jpg', 'Vodcast_5.jpg', 'Vodcast_1.jpg']

function sortPhotos(a, b) {
  return a.localeCompare(b, 'nl', { numeric: true, sensitivity: 'base' })
}

function pick(preferred, files, exclude = []) {
  const available = files.filter(f => !exclude.includes(f))
  for (const name of preferred) {
    if (available.includes(name)) return name
  }
  return available[0] ?? files[0] ?? ''
}

function run() {
  const files = readdirSync(PHOTO_DIR)
    .filter(f => /\.(jpe?g|png|webp)$/i.test(f) && !f.startsWith('.'))
    .sort(sortPhotos)

  if (files.length === 0) {
    console.error('✗ Geen foto\'s in SITE_IMAGES/VODCAST')
    process.exit(1)
  }

  const hero = files.includes(HERO_PREFERRED) ? HERO_PREFERRED : files[0]
  const longform = pick(LONGFORM_PREFERRED, files, [hero])
  const shortform = pick(SHORTFORM_PREFERRED, files, [hero, longform])
  const gallery = files.filter(f => f !== hero)

  const galleryLiteral = gallery
    .map(file => `  { src: \`${BASE}/${file}\`, altKey: 'altGallery' as const }`)
    .join(',\n')

  const body = `// Auto-generated by scripts/generate-vodcast-photos.mjs — do not edit manually.
// Bron: public/DATA_EVENTSHOOT/SITE_IMAGES/VODCAST/ — wat in de map staat, komt op de pagina.

export const VODCAST_PHOTO_BASE = '${BASE}'

export const VODCAST_HERO = \`${BASE}/${hero}\`
export const VODCAST_LONGFORM = \`${BASE}/${longform}\`
export const VODCAST_SHORTFORM = \`${BASE}/${shortform}\`

export const VODCAST_GALLERY = [
${galleryLiteral},
]
`

  mkdirSync(dirname(OUT_PATH), { recursive: true })
  writeFileSync(OUT_PATH, body, 'utf8')
  console.log(`✓ vodcastPhotos.generated.ts — hero ${hero}, galerij ${gallery.length} foto('s) uit VODCAST`)
}

run()
