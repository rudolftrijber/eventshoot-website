/**
 * Genereert src/data/siteFaq.generated.ts uit data/FAQ-import-eventshoot.csv.
 * Run: node scripts/generate-faq-data.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const CSV_PATH = join(__dirname, '../data/FAQ-import-eventshoot.csv')
const OUT_PATH = join(__dirname, '../src/data/siteFaq.generated.ts')

const PAGE_KEYS = [
  'home',
  'kennismaken',
  'eventfotografie',
  'eventvideo',
  'tarieven',
  'over-rolf',
  'voor-brancheverenigingen',
  'voor-eventbureaus',
  'voor-hotels',
  'voor-bedrijven',
  'event-vodcast-recording',
]

function parseLine(line) {
  const result = []
  let cur = ''
  let inQuotes = false
  for (let i = 0; i < line.length; i++) {
    const c = line[i]
    if (c === '"') {
      if (inQuotes && line[i + 1] === '"') {
        cur += '"'
        i++
      } else {
        inQuotes = !inQuotes
      }
    } else if (c === ';' && !inQuotes) {
      result.push(cur)
      cur = ''
    } else {
      cur += c
    }
  }
  result.push(cur)
  return result
}

function parseCsv(content) {
  const lines = content.replace(/^\uFEFF/, '').split(/\r?\n/).filter(l => l.trim())
  const headers = parseLine(lines[0])
  return lines.slice(1).map(line => {
    const cols = parseLine(line)
    const row = {}
    headers.forEach((h, i) => {
      row[h] = cols[i] ?? ''
    })
    return row
  })
}

function isActive(val) {
  const v = String(val).trim().toLowerCase()
  return v === 'ja' || v === 'yes' || v === 'true' || v === '1'
}

function esc(str) {
  return JSON.stringify(str)
}

function run() {
  const rows = parseCsv(readFileSync(CSV_PATH, 'utf8'))
  const byPage = Object.fromEntries(PAGE_KEYS.map(page => [page, { nl: [], en: [] }]))

  for (const row of rows) {
    if (!isActive(row['Actief'])) continue

    const page = row["Tonen op pagina's"]?.trim()
    if (!page || !byPage[page]) continue

    const order = Number(row['Volgorde']) || 10
    const questionNl = row['Vraag (NL)']?.trim()
    const answerNl = row['Antwoord (NL)']?.trim()
    const questionEn = row['Vraag (EN)']?.trim() || questionNl
    const answerEn = row['Antwoord (EN)']?.trim() || answerNl

    if (!questionNl || !answerNl) continue

    const id = `faq-${page}-${order}`
    byPage[page].nl.push({ _id: id, question: questionNl, answer: answerNl, sortOrder: order })
    byPage[page].en.push({ _id: id, question: questionEn, answer: answerEn, sortOrder: order })
  }

  for (const page of PAGE_KEYS) {
    byPage[page].nl.sort((a, b) => a.sortOrder - b.sortOrder)
    byPage[page].en.sort((a, b) => a.sortOrder - b.sortOrder)
    for (const lang of ['nl', 'en']) {
      byPage[page][lang] = byPage[page][lang].map(({ sortOrder: _sortOrder, ...item }) => item)
    }
  }

  const body = `// Auto-generated by scripts/generate-faq-data.mjs — do not edit manually.
import type { FaqPageKey } from '@/lib/faqPages'
import type { SanitySiteFaqItem } from '@/lib/sanity'

type FaqLangMap = Record<'nl' | 'en', SanitySiteFaqItem[]>

export const siteFaqByPage: Record<FaqPageKey, FaqLangMap> = ${JSON.stringify(byPage, null, 2)} as Record<FaqPageKey, FaqLangMap>
`

  mkdirSync(dirname(OUT_PATH), { recursive: true })
  writeFileSync(OUT_PATH, body, 'utf8')
  console.log(`✓ siteFaq.generated.ts — ${rows.length} CSV-rijen verwerkt`)
}

run()
